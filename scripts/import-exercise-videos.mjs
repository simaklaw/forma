import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { slugify } from './lib/exerciseImportRules.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUTPUT = path.join(
  ROOT,
  'apps/mobile/src/features/workout/exerciseVideoManifest.generated.ts'
);
const LIBRARY_FILE = path.join(
  ROOT,
  'apps/mobile/src/features/workout/importedExerciseLibrary.generated.ts'
);

/** Scan regular files only; symlinks cannot escape the dataset or introduce cycles. */
export function collectMp4Files(rootDir) {
  const files = new Map();
  function walk(dir) {
    for (const entry of fs
      .readdirSync(dir, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile() && /\.mp4$/i.test(entry.name)) {
        const key = entry.name.toLowerCase();
        const paths = files.get(key) ?? [];
        paths.push(path.relative(rootDir, full).split(path.sep).join('/'));
        files.set(key, paths);
      }
    }
  }
  walk(rootDir);
  return files;
}

export function createManifest(library, available, rawBase, sourceUrl, sourceLicense) {
  const base = new URL(rawBase);
  if (
    !['https:', 'http:'].includes(base.protocol) ||
    base.search ||
    base.hash ||
    base.username ||
    base.password
  ) {
    throw new Error(
      'EXERCISE_VIDEO_RAW_BASE must be an HTTP(S) directory URL without credentials, query or fragment'
    );
  }
  const manifest = [];
  for (const entry of library) {
    const slug = entry.id.replace(/^lib-/, '');
    const underscored = slug.replace(/-/g, '_');
    const nameSlug = slugify(entry.nameEn);
    const candidates = [
      slug,
      `${slug}_male`,
      `${slug}-male`,
      underscored,
      `${underscored}_male`,
      nameSlug,
      `${nameSlug}_male`
    ];
    const match = candidates
      .map((name) => available.get(`${name.toLowerCase()}.mp4`))
      .find(Boolean);
    if (!match) continue;
    if (match.length !== 1) throw new Error(`Ambiguous video for ${entry.id}: ${match.join(', ')}`);
    manifest.push({
      id: entry.id,
      videoUrl: `${base.href.replace(/\/$/, '')}/${match[0].split('/').map(encodeURIComponent).join('/')}`,
      sourceLicense,
      sourceUrl
    });
  }
  return manifest;
}

/** Local MP4 files must also be uploaded under the same relative paths at rawBase. */
export function main({
  sourceDir = process.argv[2],
  outputFile = DEFAULT_OUTPUT,
  libraryFile = LIBRARY_FILE,
  rawBase = process.env.EXERCISE_VIDEO_RAW_BASE,
  sourceUrl = process.env.EXERCISE_VIDEO_SOURCE_URL ??
    'https://github.com/harshvishu/free-exercise-db-with-videos',
  sourceLicense = process.env.EXERCISE_VIDEO_SOURCE_LICENSE ?? 'MIT'
} = {}) {
  if (!sourceDir || !fs.existsSync(sourceDir) || !fs.statSync(sourceDir).isDirectory()) {
    throw new Error(
      'Pass an existing directory containing MP4 files: node scripts/import-exercise-videos.mjs /path/to/videos'
    );
  }
  if (!rawBase)
    throw new Error(
      'Set EXERCISE_VIDEO_RAW_BASE to the directory URL where the MP4 files are hosted'
    );
  const raw = fs.readFileSync(libraryFile, 'utf8');
  const match = raw.match(/IMPORTED_EXERCISE_LIBRARY[^=]*=\s*(\[[\s\S]*?\n\]);/);
  if (!match) throw new Error('Could not locate IMPORTED_EXERCISE_LIBRARY array');
  const library = JSON.parse(match[1]);
  const available = collectMp4Files(sourceDir);
  const files = [...available.values()].flat();
  const manifest = createManifest(library, available, rawBase, sourceUrl, sourceLicense);
  // An incorrect dataset path must not erase a previously useful manifest.
  if (!manifest.length)
    throw new Error('No matching MP4 files found; existing manifest left unchanged');
  const output = `/** AUTO-GENERATED by scripts/import-exercise-videos.mjs. */
export interface ExerciseVideoManifestEntry {
  id: string;
  videoUrl: string;
  sourceLicense: string;
  sourceUrl: string;
}
export const EXERCISE_VIDEO_MANIFEST: ExerciseVideoManifestEntry[] = ${JSON.stringify(manifest, null, 2)};
`;
  fs.writeFileSync(outputFile, output);
  console.log(`MP4 files found: ${files.length}`);
  console.log('Sample files:', files.slice(0, 15));
  console.log(`Matched ${manifest.length} / ${library.length} exercises. Manifest: ${outputFile}`);
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
